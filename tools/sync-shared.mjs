#!/usr/bin/env node
// Copies shared/<family>/*.mjs into skills/<family>/<skill>/scripts/lib/ and shared/<family>/references/*.md into
// skills/<family>/<skill>/references/ so each skill folder stays self-contained. Each skill gets only what it uses:
// libs its scripts import as ./lib/<x>.mjs (plus whatever those import from shared/, transitively), and references
// its SKILL.md links to as references/<x>.md. Generated copies a skill no longer uses are deleted; files without the
// GENERATED header are never touched.
// Usage: node tools/sync-shared.mjs [--check | --dry-run]
//   --check    exit 1 if any copy is missing, stale, or no longer used
//   --dry-run  print what would be written and deleted, change nothing

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, dirname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const dryRun = process.argv.includes('--dry-run');
const MARKER = 'GENERATED by tools/sync-shared.mjs';
const notice = (source) => `${MARKER} — do not edit. Edit ${source} and run \`npm run sync\`.`;

// .mjs: header comment on line 1. .md: HTML comment right after the frontmatter so frontmatter stays first.
const withHeader = {
  mjs: (source, text) => `// ${notice(source)}\n${text}`,
  md: (source, text) => {
    const comment = `<!-- ${notice(source)} -->\n`;
    const frontmatter = text.match(/^---\n[\s\S]*?\n---\n/);
    return frontmatter ? frontmatter[0] + comment + text.slice(frontmatter[0].length) : comment + text;
  },
};

// Static and dynamic relative imports: `from './x.mjs'`, `import './x.mjs'`, `import('./x.mjs')`.
const IMPORT = /(?:\bfrom|\bimport)\s*\(?\s*['"](\.\/[^'"]+\.mjs)['"]/g;
// Inline markdown links, ignoring images; fenced code blocks are stripped first.
const LINK = /(?<!!)\[[^\]]*\]\(([^)\s#]+)(?:#[^)\s]*)?\)/g;

const listDirs = (dir) => (existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name) : []);
const listFiles = (dir, ext) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(`.${ext}`)) : []);
// Only files carrying the header written by withHeader count as generated copies.
const isGenerated = { mjs: (text) => text.startsWith(`// ${MARKER}`), md: (text) => text.includes(`<!-- ${MARKER}`) };
const importsOf = (text, prefix) =>
  [...text.matchAll(IMPORT)].map((m) => m[1]).filter((spec) => spec.startsWith(prefix)).map((spec) => spec.slice(prefix.length));

// Shared libs a skill needs: its scripts' ./lib/ imports, closed over imports between shared files.
function libsFor(skillDir, sharedDir) {
  const scriptsDir = join(skillDir, 'scripts');
  const queue = listFiles(scriptsDir, 'mjs').flatMap((f) => importsOf(readFileSync(join(scriptsDir, f), 'utf8'), './lib/'));
  const needed = new Set();
  while (queue.length) {
    const file = queue.shift();
    if (needed.has(file)) continue;
    const path = join(sharedDir, file);
    if (!existsSync(path)) throw new Error(`${skillDir}: imports ./lib/${file}, but ${path} does not exist.`);
    needed.add(file);
    queue.push(...importsOf(readFileSync(path, 'utf8'), './'));
  }
  return needed;
}

// Shared references a skill's SKILL.md links to as references/<file>.md.
function refsFor(skillDir, sharedRefs) {
  const skillMd = join(skillDir, 'SKILL.md');
  if (!existsSync(skillMd)) return new Set();
  const prose = readFileSync(skillMd, 'utf8').replace(/```[\s\S]*?```/g, '');
  const linked = [...prose.matchAll(LINK)].map((m) => posix.normalize(m[1])).filter((p) => posix.dirname(p) === 'references');
  return new Set(linked.map((p) => posix.basename(p)).filter((f) => sharedRefs.includes(f)));
}

const stale = [];
const extra = [];
let written = 0;
let deleted = 0;
for (const family of listDirs(join(root, 'shared'))) {
  const sharedDir = join(root, 'shared', family);
  const sharedRefs = listFiles(join(sharedDir, 'references'), 'md');
  for (const skill of listDirs(join(root, 'skills', family))) {
    const skillDir = join(root, 'skills', family, skill);
    // [ext, shared subdir, skill subdir, files this skill needs]
    const groups = [
      ['mjs', '', join('scripts', 'lib'), libsFor(skillDir, sharedDir)],
      ['md', 'references', 'references', refsFor(skillDir, sharedRefs)],
    ];
    for (const [ext, sourceSub, targetSub, needed] of groups) {
      const sourceDir = join(sharedDir, sourceSub);
      const targetDir = join(skillDir, targetSub);
      const rel = (file) => ['skills', family, skill, targetSub, file].join('/');
      for (const file of [...needed].sort()) {
        const source = ['shared', family, sourceSub, file].filter(Boolean).join('/');
        const expected = withHeader[ext](source, readFileSync(join(sourceDir, file), 'utf8'));
        const target = join(targetDir, file);
        const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
        if (current === expected) continue;
        if (check) {
          stale.push(rel(file));
        } else {
          if (dryRun) console.error(`would write  ${rel(file)}`);
          else {
            mkdirSync(targetDir, { recursive: true });
            writeFileSync(target, expected);
          }
          written++;
        }
      }
      for (const file of listFiles(targetDir, ext)) {
        if (needed.has(file) || !isGenerated[ext](readFileSync(join(targetDir, file), 'utf8'))) continue;
        if (check) {
          extra.push(rel(file));
        } else {
          if (dryRun) console.error(`would delete ${rel(file)}`);
          else rmSync(join(targetDir, file));
          deleted++;
        }
      }
    }
  }
}

if (check && (stale.length || extra.length)) {
  if (stale.length) console.error(`Out of sync (run \`npm run sync\`):\n  ${stale.join('\n  ')}`);
  if (extra.length) console.error(`Generated copies no longer used (run \`npm run sync\` to delete):\n  ${extra.join('\n  ')}`);
  process.exit(1);
}
const verb = dryRun ? 'Would sync' : 'Synced';
console.error(check ? 'Shared files in sync.' : `${verb} ${written} file(s), ${dryRun ? 'would delete' : 'deleted'} ${deleted} unused generated copy(ies).`);
