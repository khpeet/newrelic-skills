import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'tools', 'sync-shared.mjs');
const MARKER = 'GENERATED by tools/sync-shared.mjs';

// A throwaway repo: tools/sync-shared.mjs plus one family with one shared lib, one shared reference, and one skill that uses both.
function fixture() {
  const root = mkdtempSync(join(tmpdir(), 'sync-shared-'));
  const put = (rel, text) => {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), text);
  };
  mkdirSync(join(root, 'tools'));
  cpSync(SCRIPT, join(root, 'tools', 'sync-shared.mjs'));
  put('shared/fam/util.mjs', 'export const x = 1;\n');
  put('shared/fam/references/ref.md', '---\nsource: https://example.com\n---\n# Ref\n');
  put('skills/fam/s1/SKILL.md', '---\nname: s1\n---\nSee [ref](references/ref.md).\n');
  put('skills/fam/s1/scripts/a.mjs', "import { x } from './lib/util.mjs';\nconsole.log(x);\n");
  return { root, put, read: (rel) => readFileSync(join(root, rel), 'utf8'), exists: (rel) => existsSync(join(root, rel)) };
}

const sync = (root, ...args) => spawnSync(process.execPath, [join(root, 'tools', 'sync-shared.mjs'), ...args], { encoding: 'utf8' });

test('sync copies only what a skill uses, with the GENERATED header (after frontmatter for .md)', () => {
  const { root, read, exists } = fixture();
  assert.equal(sync(root).status, 0);
  assert.ok(read('skills/fam/s1/scripts/lib/util.mjs').startsWith(`// ${MARKER}`));
  const ref = read('skills/fam/s1/references/ref.md');
  assert.match(ref, new RegExp(`^---\\nsource: https://example.com\\n---\\n<!-- ${MARKER}`));
  assert.ok(!exists('skills/fam/s1/scripts/lib/other.mjs'));
  assert.equal(sync(root, '--check').status, 0);
});

test('sync --check fails on drift and on an unused generated copy', () => {
  const { root, put } = fixture();
  sync(root);
  put('shared/fam/util.mjs', 'export const x = 2;\n');
  const drift = sync(root, '--check');
  assert.equal(drift.status, 1);
  assert.match(drift.stderr, /Out of sync[\s\S]*util\.mjs/);
  sync(root);
  put('skills/fam/s1/scripts/a.mjs', 'console.log(1);\n');
  const unused = sync(root, '--check');
  assert.equal(unused.status, 1);
  assert.match(unused.stderr, /no longer used[\s\S]*util\.mjs/);
});

test('sync deletes an unused generated copy, but never a hand-written file that merely quotes the marker', () => {
  const { root, put, exists } = fixture();
  sync(root);
  put('skills/fam/s1/SKILL.md', '---\nname: s1\n---\nNo links.\n');
  put('skills/fam/s1/references/notes.md', `# My notes\n\nThe header looks like \`<!-- ${MARKER} -->\`.\n`);
  put('skills/fam/s1/references/framed.md', `---\nname: x\n---\n# Notes\n\nQuoted: <!-- ${MARKER} -->\n`);
  const result = sync(root);
  assert.equal(result.status, 0, result.stderr);
  assert.ok(!exists('skills/fam/s1/references/ref.md'), 'the unused generated reference is deleted');
  assert.ok(exists('skills/fam/s1/references/notes.md'), 'a hand-written file quoting the marker is kept');
  assert.ok(exists('skills/fam/s1/references/framed.md'), 'a hand-written file with frontmatter quoting the marker is kept');
});

test('sync --dry-run changes nothing', () => {
  const { root, exists } = fixture();
  const result = sync(root, '--dry-run');
  assert.equal(result.status, 0);
  assert.match(result.stderr, /would write/);
  assert.ok(!exists('skills/fam/s1/scripts/lib/util.mjs'));
});
